EncryptionKey::Data GenerateSecret() {
    // Это безопасный способ сгенерировать секрет, под капотом openssl
    // Телеграм тоже использует это для генерации DH секретов
    EncryptionKey::Data random;
    bytes::set_random(random);
    return random;
}

EncryptionKeyPtr GenerateKey() {
    // Используется только для saved messages
    return std::make_shared<EncryptionKey>(GenerateSecret());
}

