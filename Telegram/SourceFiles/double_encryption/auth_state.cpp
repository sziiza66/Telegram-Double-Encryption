static constexpr uint32 GoodGs[] = {3, 4, 5, 7};

uint32 GetGoodG() {
    uint8 byte;
    bytes::set_random(bytes::make_span(&byte, 1));
    return GoodGs[byte % (sizeof(GoodGs) / sizeof(GoodGs[0]))];
}

void ClearBytes(bytes::span bytes) {
    OPENSSL_cleanse(bytes.data(), bytes.size());
}

